## This code can attempt to quantitatively determine an appropriate number of principle components to use
##    as input for functions that use PCA data as input. It will calculate this value by running the following calculations
##    on the PCA data generated by Seurat's RunPCA() function:
##    Method A) The code will identify the lowest number PC among the PCs that explain >= PCs_CumulPctVar_Threshold 
##                of the cumulative variance that itself explains < PCs_AbsVar_Threshold variance
##              Or, in less technical terms, the code will identify the minimal set of principle components that explain at least
##                X % of the total variance, then check to see if any of the PCs not included in this set actually explain a
##                fairly large amount of variance. 
##              For example, let's say you set the cumulative variance threshold to 80% and the absolute variance threshold to 5%, and
##                you have a dataset with 15 PCs. The code would figure out that, e.g., PCs 1:10 explain 80% of the total variance, but
##                PC 11 explains 7% of the remaining variance while PCs 12-15 each explain less than 5% each. So, Method A here
##                would return PCs 1:11 as the recommended set to use for dimensional reduction.
##    Method B) This method attempts to identify the point of diminishing returns in the PCA reduction by using an 
##                algebraic short-cut to estimate the location of the 'elbow' in an ElbowPlot. The code will calculate the difference
##                in variance explained between each sequential set of PCs (i.e., PC1 - PC2, PC2 - PC3, etc.) and identify the highest
##                PC after which the difference in variance between all subsequent PCs is < PC_DeltaVar_Threshold
##              So basically, we are identifying the PC after which additional PCs fail to explain much more variance than the preceding PCs.
##    The code will then compare the PC # determined by Method A and Method B and use the lower of the two.


## If you would prefer to define the number of PCs for clustering functions yourself
##    instead of using mathematical calculation of optimal PCs, set this
##    use_automated_nPCs_calc toggle to false and enter your desired max PCs in the
##    nPCs_for_cluster_fxns variable.
## If use_automated_nPCs_calc is set to TRUE, the value in nPCs_for_cluster_fxns will be
##    over-written later in the code.
