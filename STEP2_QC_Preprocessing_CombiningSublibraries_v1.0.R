  ## The general goal of integration is to take data from, e.g., two experimental conditions, and align it 
  ##    so that cells from the same cell type/subpopulation will cluster together. In other words, the goal is
  ##    to go from having two clusters [Condition 1 - Cell Type A] and [Condition 2 - Cell Type A] to having
  ##    a single cluster [Cell Type A] without discarding any of the information that distinguishes Condition 1
  ##    from Condition 2.
  
  ## From the Seurat Vignette: "We often refer to this procedure as intergration/alignment. When aligning 
  ##    two genome sequences together, identification of shared/homologous regions can help to interpret differences 
  ##    between the sequences as well. Similarly for scRNA-seq integration, our goal is not to remove biological 
  ##    differences across conditions, but to learn shared cell types/states in an initial step - specifically because 
  ##    that will enable us to compare control stimulated and control profiles for these individual cell types.
  
  ## The Seurat v5 integration procedure aims to return a single dimensional reduction that captures the shared 
  ##    sources of variance across multiple layers, so that cells in a similar biological state will cluster. The 
  ##    method returns a dimensional reduction (i.e. integrated.cca) which can be used for visualization and
  ##    unsupervised clustering analysis.
  
  
