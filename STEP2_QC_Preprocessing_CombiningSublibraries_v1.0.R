if (use_automated_nPCs_calc) {
  stdv <- seurat_integrations[["pca"]]@stdev
  sum.stdv <- sum(seurat_integrations[["pca"]]@stdev)
  percent.stdv <- (stdv / sum.stdv) * 100
  cumulative <- cumsum(percent.stdv)
  co1 <- which(cumulative > PCs_CumulPctVar_Threshold & percent.stdv < PCs_AbsVar_Threshold)[1]
  co2 <- sort(which((percent.stdv[1:length(percent.stdv) - 1] - 
                       percent.stdv[2:length(percent.stdv)]) > PC_DeltaVar_Threshold), 
              decreasing = T)[1] + 1
  nPCs_for_cluster_fxns <- min(co1, co2)
  nPCs_for_cluster_tracker <- c(nPCs_for_cluster_tracker,paste0('seurat_integrations nPCs = ',as.character(nPCs_for_cluster_fxns)))
}
  
