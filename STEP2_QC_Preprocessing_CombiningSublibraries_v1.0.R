  QC_filtering_stats[1,i] <- pre_filter_cell_counts[(i-1),2]
  QC_filtering_stats[2,i] <- post_filter_cell_counts[(i-1),2]
  QC_filtering_stats[3,i] <- pre_filter_cell_counts[(i-1),2] - post_filter_cell_counts[(i-1),2]
