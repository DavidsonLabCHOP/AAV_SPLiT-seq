## This function adds a Cell_Complexity column to the meta.data. Cell Complexity is
##    a measurement of how many genes are detected vs total UMI counts. A low complexity
##    value generally indicates that a cell had low gene detection but comparatively high
##    UMI counts in these detected genes. As UMI counts increase, that should mean our
##    coverage of a cell increases, which in turn should mean that we will detect more genes.
##    If UMI counts are high relative to the number of genes detected, then something is
##    wrong (e.g., the cell was undergoing apoptosis and shutting down gene transcription).
##    So, it's a good idea to filter out low complexity cells.
seurat_merged <- Add_Cell_Complexity_Seurat(seurat_merged)

## This function adds columns to the meta.data containing info on the % of detected
##    genes that are mitochondrial or ribosomal.
## Low-quality / dying cells often exhibit high levels of mitochondrial contamination,
##    so this is a commonly used metric for cell filtering
## The Seurat vingette uses a 5% filter; The original version of this code was using
##    a less stringent 10% filter.
seurat_merged <- Add_Mito_Ribo_Seurat(seurat_merged, species =  "human")



