## The following chunk of code will run doublet finder to identify doublets in the seurat_filtered
##    object and remove them. The doublet finder function requires a number of variables,
##    the most important of which is the expected number of real doublets in your data. The function
##    will basically find as many doublets as you tell it to.
## Conveniently, Ashley has this function set up to automatically calculate values for the key variables
##    needed to run doublet finder based on the dataset it is analyzing. The one exception is the
##    expected percent of doublets, which needs to be determined by the user and dfined using the
##    Expected_Pct_Doublets variable below.

if (run_doublet_finder) {
  
  Expected_Pct_Doublets <- 0.1
  
  ## pN: the number of artificial doublets, represented as a fraction 
  ## pK: the neighorhood size used to compute the number of artifical nearest neighbors
  ## Exp: the number of expected real doublets
  ## Pre-process Seurat object (standard) ------------------------------------------------------
  # Perform Seurat preprocessing on Merged plate1 seurat object.  
  
  ## Seurat objects need to be fully pre-processed prior to doublet removal. However,
  ##    this pre-processing is performed within the loop below so it does not need to be completed
  ##    prior to feeding the seurat_filtered object into the following chunk of code.
  
  set.seed(100)
  
  seurat.list <- SplitObject(seurat_filtered, split.by = "orig.ident") #or try by sublibrary
  #length(seurat.list)
  
  #names(seurat.list)
  #length(seurat.list)
  
  # loop through samples to find doublets
  for (i in 1:length(seurat.list)) {
    # print the sample we are on
    print(paste0("Sample ",i, " of ", length(seurat.list)))
    
    # Pre-process seurat object with standard seurat workflow
    sample <- NormalizeData(seurat.list[[i]])
    sample <- FindVariableFeatures(sample, nfeatures = nVariableFeatures)
    sample <- ScaleData(sample)
    sample <- RunPCA(sample)
    
    ## The following code attempts to mathematically determine the appropriate number
    ##    of principle components to use in subsequent functions that use PCA dimensional
    ##    reduction data as input.
    if (use_automated_nPCs_calc) {
      stdv <- sample[["pca"]]@stdev
      sum.stdv <- sum(sample[["pca"]]@stdev)
      percent.stdv <- (stdv / sum.stdv) * 100
      cumulative <- cumsum(percent.stdv)
      co1 <- which(cumulative > PCs_CumulPctVar_Threshold & percent.stdv < PCs_AbsVar_Threshold)[1]
      co2 <- sort(which((percent.stdv[1:length(percent.stdv) - 1] - 
                           percent.stdv[2:length(percent.stdv)]) > PC_DeltaVar_Threshold), 
                  decreasing = T)[1] + 1
      nPCs_for_cluster_fxns <- min(co1, co2)
      nPCs_for_cluster_tracker <- c(nPCs_for_cluster_tracker,paste0('DoubletFinder - ',sublibrary_IDs[i],' nPCs = ',as.character(nPCs_for_cluster_fxns)))
    }

    # finish pre-processing
    sample <- FindNeighbors(object = sample, dims = 1:nPCs_for_cluster_fxns)              
    sample <- FindClusters(object = sample)
    ## sample <- RunUMAP(sample, dims = 1:20) ## Doublet finder appears to use tSNE, not UMAP,
    ##                                           so I'm removing this step to speed up the code
    sample <- RunTSNE(sample, assay = "RNA")
    # Find significant PCs

    #nPCs_for_cluster_fxns
    
    # pK identification (no ground-truth)
    sweep.list <- paramSweep(sample, PCs = 1:nPCs_for_cluster_fxns)
    sweep.stats <- summarizeSweep(sweep.list)
    bcmvn <- find.pK(sweep.stats)
    
    # Optimal pK is the max of the bomodality coefficent (BCmvn) distribution
    bcmvn.max <- bcmvn[which.max(bcmvn$BCmetric),]
    optimal.pk <- bcmvn.max$pK
    optimal.pk <- as.numeric(levels(optimal.pk))[optimal.pk]
    
    ## Homotypic doublet proportion estimate
    annotations <- sample@meta.data$seurat_clusters
    homotypic.prop <- modelHomotypic(annotations) 
    nExp.poi <- round(Expected_Pct_Doublets*nrow(sample@meta.data)) 
    nExp.poi.adj <- round(nExp.poi * (1 - homotypic.prop))
    
    sample <- RunTSNE(sample)
    # run DoubletFinder
    sample <- doubletFinder(seu = sample, 
                            PCs = 1:nPCs_for_cluster_fxns, 
                            pK = optimal.pk,
                            nExp = nExp.poi.adj)
    metadata <- sample@meta.data
    
    ## If you've copied this function from another version of this code and it isn't working
    ##    properly on your multi-assay seurat object, it is because you need to update the
    ##    line of code below.
    colnames(metadata)[ncol(metadata)] <- "doublet_finder"
    sample@meta.data <- metadata
    
    #save doublet identity in seurat metadata
    seurat.list[[i]] <- sample
    remove(sample)
  }
  rm(sweep.list)
  
  
  ##############################################
  ##
  ##  Doublet finder loop complete. Merging processed seurat objects.
  ##
  
  ## Merge_Seurat_List is convenient, but it appears to automatically attempt to append tags from
  ##    the add.cell.ids option. If you leave that option empty, the merge will work fine, but all your
  ##    cell names will end up with a "_" at the beginning (i.e., it doesn't add any cell ID tags, but
  ##    it still adds the spacer between the non-existant cell ID tag and the original cell name)
  seurat.doubletfinder <- merge(seurat.list[[1]], y = unlist(seurat.list[2:length(seurat.list)]))
