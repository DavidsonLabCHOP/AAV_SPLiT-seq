  DoubletViolinPlots <- VlnPlot(seurat.doubletfinder, features = c("nFeature_RNA", "nCount_RNA","percent_mito"), group.by = "doublet_finder", log = TRUE, pt.size = 0, combine=FALSE) 
  Doublet_nFeature <- DoubletViolinPlots[[1]] + geom_boxplot(outlier.shape=NA, width=.2, fill='white')
