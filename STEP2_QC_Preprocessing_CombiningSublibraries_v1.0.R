    doublet_finder_stats[,(i+1)] <- doublet_finder_results$Freq
  }
  
  doublet_finder_stats$Totals <- rowSums(doublet_finder_stats[,c(2:ncol(doublet_finder_stats))])
  #filtering_stats <- rbind(filtering_stats, doublet_finder_stats)
  
  metadata <- seurat.doubletfinder@meta.data
  
  for (x in 2:length(Seurat::Assays(seurat.doubletfinder))) {
