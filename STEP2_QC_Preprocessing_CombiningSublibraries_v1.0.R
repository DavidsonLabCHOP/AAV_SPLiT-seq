  wrap_plots(Doublet_nFeature, Doublet_nCount, Doublet_nMito, ncol = 3)
  
  
  
  
  ################################
  ##
  ##  Dimensionality Reduction and Feature Mapping Plots
  ##
  
  ## Prior to plotting dimensionality reductions and related plots, we need to run seurat.doubletfinder
  ##    through the standard seurat workflow.
  ## Note: this is a slight alteration of the standard workflow because it is using 3500
  ##    features as the value for FindVariableFeatures instead of 2000 which is the default.
  ##    The Seurat documentation suggests that generally more is better as far as nfeatures goes.
  ##    The reason for this is that higher numbers of nfeatures allow better estimates of the
  ##    variance calculations associated with dimensionality reductions, specifically PCAs in this case.
  
  Idents(seurat.doubletfinder) <- 'orig.ident'
  seurat.doubletfinder <- NormalizeData(object = seurat.doubletfinder) %>%
    FindVariableFeatures(nfeatures = nVariableFeatures) %>%
    ScaleData() %>%
    RunPCA()
  
  if (use_automated_nPCs_calc) {
    stdv <- seurat.doubletfinder[["pca"]]@stdev
    sum.stdv <- sum(seurat.doubletfinder[["pca"]]@stdev)
    percent.stdv <- (stdv / sum.stdv) * 100
    cumulative <- cumsum(percent.stdv)
    co1 <- which(cumulative > PCs_CumulPctVar_Threshold & percent.stdv < PCs_AbsVar_Threshold)[1]
    co2 <- sort(which((percent.stdv[1:length(percent.stdv) - 1] - 
