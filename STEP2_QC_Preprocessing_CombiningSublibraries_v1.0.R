## Note: sublibrary_IDs is created at the top of the script
artifact_filtering_stats <- data.frame(matrix(nrow=3,ncol=(length(sublibrary_IDs)+1)))
colnames(artifact_filtering_stats) <- c('Metric',sublibrary_IDs)
artifact_filtering_stats$Metric <- c('nCells_PreArtifactFilter','n_ArtifactCells','nCells_PostArtifactFilter')

## First, I'm calculating the number of cells pre- and post-filtering for each sublibrary
for (i in 2:ncol(artifact_filtering_stats)) {
  artifact_filtering_stats[1,i] <- pre_filter_cell_counts[(i-1),2]
  artifact_filtering_stats[2,i] <- artifact_cell_counts[(i-1),2]
  artifact_filtering_stats[3,i] <- pre_filter_cell_counts[(i-1),2] - artifact_cell_counts[(i-1),2]
}

## Now I'm handling the much more difficult task of counting the number of transduced cells
##    for each sublibrary. This gets complicated because I've written everything so that it will work 
##    regardless of the number or identity of the serotypes present in the data.
metadata <- seurat_merged@meta.data

for (x in 2:length(Seurat::Assays(seurat_merged))) {
  assay_name <- Seurat::Assays(object = seurat_merged)[x]
  serotype <- str_split(assay_name, pattern = "_")[[1]][1]
  metadata_column_name <- paste0(serotype,'_transduction')
  assay_stats <- data.frame(matrix(nrow=3,ncol=ncol(artifact_filtering_stats)))
  colnames(assay_stats) <- colnames(artifact_filtering_stats)
  assay_stats$Metric[1] <- paste0('nCells_PreArtifactFilter_',serotype)
  assay_stats$Metric[2] <- paste0('n_ArtifactCells_',serotype)
  assay_stats$Metric[3] <- paste0('nCells_PostArtifactFilter_',serotype)
  
  for (i in 1:length(sublibrary_IDs)) {
    metadata_pull <- metadata[metadata$orig.ident == sublibrary_IDs[i],]
    prefilter_stats <- as.data.frame(table(metadata_pull[,metadata_column_name]))
    assay_stats[1,i+1] <- prefilter_stats[2,2]
    assay_stats[2,i+1] <- sum(metadata_pull$ArtifactCells[metadata_pull[,metadata_column_name]==TRUE])
    assay_stats[3,i+1] <- assay_stats[1,i+1] - assay_stats[2,i+1]
  }
  
  artifact_filtering_stats <- rbind(artifact_filtering_stats,assay_stats)
}

artifact_filtering_stats$Totals <- rowSums(artifact_filtering_stats[,c(2:ncol(artifact_filtering_stats))])



