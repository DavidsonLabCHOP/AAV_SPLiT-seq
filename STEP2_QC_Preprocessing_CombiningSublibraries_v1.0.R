  ##    doublet_finder (we actually define the name of this variable in the code above) that
  ##    contains the Singlet or Doublet classification for each cell. And another column called
  ##    "pANN_[bunch of numbers]" that contains the value of the metric doublet finder uses to
  ##    identify doublets. 
  ## We are only interested in the Singlet vs Doublet classification produced by doublet finder.
  ##    So, to clean up the resulting meta.data, the following code will remove the "pANN_..."
  ##    columns.
  
  metadata <- seurat.doubletfinder@meta.data
  gratuitous_metadata <- grep('pANN',colnames(metadata))
  metadata <- metadata[,-gratuitous_metadata]
  seurat.doubletfinder@meta.data <- metadata 
  
  
  
