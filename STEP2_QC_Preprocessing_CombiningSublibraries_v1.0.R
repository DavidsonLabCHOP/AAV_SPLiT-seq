    assay_stats$Metric[1] <- paste0(serotype,'_Doublets')

    for (i in 1:length(sublibrary_IDs)) {
      metadata_pull <- metadata[metadata$orig.ident == sublibrary_IDs[i],]
      metadata_pull <- metadata_pull[metadata_pull$doublet_finder == 'Doublet',]
      assay_stats[1,i+1] <-  sum(metadata_pull[,metadata_column_name] == TRUE)
    }
    assay_stats$Totals <- rowSums(assay_stats[,c(2:(ncol(assay_stats)-1))])
    doublet_finder_stats <- rbind(doublet_finder_stats,assay_stats)
  }
  
  
  
  ###################################
  ##
  ##  Doublet finder QC plots
  ##  
  ###################################
  
  ################################
  ##
  ##  Basic QC Plots
  ##
  
  ## Visualize QC Data for Doublets vs Singlets
  ## Note: The figures created by the following code are meant to be viewed in R. There is code
