                decreasing = T)[1] + 1
    nPCs_for_cluster_fxns <- min(co1, co2)
    nPCs_for_cluster_tracker <- c(nPCs_for_cluster_tracker,paste0('seurat.doubletfinder nPCs = ',as.character(nPCs_for_cluster_fxns)))
  }
  
  seurat.doubletfinder <- seurat.doubletfinder %>%
    FindNeighbors(dims = 1:nPCs_for_cluster_fxns) %>%
    FindClusters(resolution = FindClusterResolution) %>%
    RunUMAP(dims = 1:nPCs_for_cluster_fxns)
  
  
  

  
  
  
  ## While interesting on their own, many of these dimensionality reduction plots are most
