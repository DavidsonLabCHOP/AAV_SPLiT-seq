    assay_stats$Metric[2] <- paste0('nCell_PostFilter_',serotype)
    assay_stats$Metric[3] <- paste0('nCell_Filtered_',serotype)
    
  for (i in 1:length(sublibrary_IDs)) {
      prefilter_metadata_pull <- prefilter_metadata[prefilter_metadata$orig.ident == sublibrary_IDs[i],]
      postfilter_metadata_pull <- postfilter_metadata[postfilter_metadata$orig.ident == sublibrary_IDs[i],]
    
      prefilter_stats <- as.data.frame(table(prefilter_metadata_pull[,metadata_column_name]))
      assay_stats[1,i+1] <- prefilter_stats[2,2]
      postfilter_stats <- as.data.frame(table(postfilter_metadata_pull[,metadata_column_name]))
      assay_stats[2,i+1] <- postfilter_stats[2,2]
      assay_stats[3,i+1] <- prefilter_stats[2,2] - postfilter_stats[2,2]
  }
    
  QC_filtering_stats <- rbind(QC_filtering_stats,assay_stats)
}

